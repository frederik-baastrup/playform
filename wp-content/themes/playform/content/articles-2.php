<h2>Er det noget for dig?</h2>
<ul>
<li><strong>Ja,</strong> hvis du allerede går til reformer-pilates og vil træne mere, eller hvis du gerne vil have skånsom styrketræning hjemme.</li>
<li><strong>Måske,</strong> hvis du er helt ny. Tag gerne et par hold først, så du kender øvelserne og ved, at du kan lide det.</li>
<li><strong>Nej,</strong> hvis du ikke har plads – så er pilates på <a href="/yoga-pilates/yogamaatte/">måtte</a> med lidt tilbehør et godt alternativ.</li>
</ul>

<h2>Plads</h2>
<p>En reformer er lang, typisk over to meter, og du skal have plads omkring den til at træne. Nogle modeller kan klappes sammen eller stilles på højkant, hvilket gør dem langt nemmere at have i en stue. Mål op, før du køber, og husk at tjekke de sammenklappede mål.</p>

