<h2>Tilbehør, der udvider racket</h2>
<ul>
<li><strong>Dip-håndtag:</strong> til dips for bryst og triceps.</li>
<li><strong>Kabeltræk eller lat-pulldown:</strong> gør racket til et lille multigym med rygøvelser og triceps.</li>
<li><strong>Landmine:</strong> en holder til stangens ende, der giver mange nye øvelser til hele kroppen.</li>
<li><strong>Pinde til skiver:</strong> holder orden og gør racket mere stabilt.</li>
<li><strong>Pinde til elastikker:</strong> til at tilføje ekstra modstand i fx squat og bænkpres.</li>
</ul>
<p>Tjek, at tilbehøret passer til dit rack – stolpernes mål og hullernes størrelse varierer fra producent til producent.</p>

<h2>Gulvet i detaljer</h2>
<p>Et tungt rack, en bænk og vægte belaster gulvet. På et betongulv i kælder eller garage er det sjældent et problem. På et trægulv med bjælkelag kan tunge løft og tabte vægte give svaj og lyd, så overvej, hvor tungt du vil træne, og fordel vægten med en stor plade eller tykke gummifliser.</p>
<ul>
<li><strong>Gummifliser:</strong> dækker hele området og dæmper lyd og stød.</li>
<li><strong>Løfteplatform:</strong> en plade i midten med gummi i siderne, hvor vægtene lander ved markløft.</li>
<li><strong>Bumper plates:</strong> gummiskiver, der skåner gulvet, hvis vægten sættes hårdt ned.</li>
</ul>

<h2>Et simpelt program i racket</h2>
<p>Træn 2–3 gange om ugen og skift mellem to pas:</p>
<ul>
<li><strong>Pas A:</strong> squat, bænkpres, rows med stang.</li>
<li><strong>Pas B:</strong> markløft, skulderpres, pull-ups.</li>
</ul>
<p>Lav 3 sæt af 5–8 gentagelser, og øg vægten lidt, når du klarer alle gentagelser med god teknik. Start lettere, end du tror – teknikken først.</p>

<h2>Ofte stillede spørgsmål</h2>
<h3>Hvor meget loftshøjde kræver et power rack?</h3>
<p>Det varierer fra model til model. Tjek højden i produktbeskrivelsen og husk plads over stangen, hvis du vil lave pull-ups.</p>
<h3>Skal et power rack boltes fast?</h3>
<p>Nogle skal, andre står stabilt alene – især med vægtskiver på pindene. Følg producentens anvisning.</p>
<h3>Kan jeg have et power rack i en lejlighed?</h3>
<p>Det kan lade sig gøre med gummigulv og hensyn til naboerne, men tunge løft og tabte vægte giver lyd. En garage eller et kælderrum er ofte bedre.</p>
