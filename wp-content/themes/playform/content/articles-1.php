<p>Læg gummifliser eller en kraftig måtte under racket. Det beskytter gulvet, dæmper lyd og giver bedre fodfæste.</p>

[playform_produkter kategori="power-rack" antal="4"]

<h2>Det skal du kigge efter</h2>
<ul>
<li><strong>Maksimal belastning:</strong> Både racket og sikkerhedsstængerne skal kunne tage den vægt, du løfter – med god margin.</li>
<li><strong>Huller med tæt afstand:</strong> Gør det lettere at stille J-hooks og sikkerhedsstænger i præcis den rigtige højde.</li>
<li><strong>Stabilitet:</strong> Kan racket boltes fast, eller står det stabilt nok alene? Nogle racks kræver, at de boltes i gulvet.</li>
<li><strong>Tilbehør:</strong> Pull-up-stang, dip-håndtag, pinde til vægtskiver og evt. kabeltræk kan gøre racket til et helt hjemmegym.</li>
</ul>

<h2>Det skal du også bruge</h2>
<ul>
<li><strong><a href="/styrketraening/vaegte-kettlebells/vaegtstaenger/">Vægtstang</a>:</strong> En olympisk stang passer til de fleste racks.</li>
<li><strong><a href="/styrketraening/vaegte-kettlebells/vaegtskiver/">Vægtskiver</a>:</strong> Skal passe til stangen – olympiske skiver har stort hul.</li>
<li><strong><a href="/styrketraening/styrke-baenke/traeningsbaenk/">Træningsbænk</a>:</strong> Til bænkpres i racket. Tjek, at den passer i bredden.</li>
<li><strong>Låse til stangen:</strong> Så skiverne ikke glider.</li>
</ul>

<h2>Sikkerhed, når du træner alene</h2>
<ul>
<li>Stil sikkerhedsstængerne lige under den laveste position i øvelsen.</li>
<li>Brug låse på stangen.</li>
<li>Øv dig i at "dumpe" vægten på sikkerhedsstængerne med en let vægt, så du ved, hvordan det føles.</li>
<li>Byg vægten langsomt op, og prioritér teknik.</li>
</ul>

<h2>Er et multigym et alternativ?</h2>
<p>Et <a href="/styrketraening/styrke-baenke/multigym/">multigym</a> har styrede bevægelser og en vægtstak, så du ikke skal bruge løse skiver. Det er sikkert og nemt alene, men fylder meget og giver ikke de samme muligheder for tunge frie løft. Vil du squatte og bænkpresse tungt, er et rack det bedste valg.</p>
<p>Se <a href="/styrketraening/styrke-baenke/power-rack/">alle power racks</a> og <a href="/styrketraening/">alt til styrketræning</a>.</p>

<h2>Hvad koster et power rack?</h2>
<p>Da vi skrev artiklen, lå de fleste power racks, half racks og squat stands hos butikkerne på Playform mellem ca. 2.000 og 13.000 kr. De billigste er typisk squat stands og lettere racks, mens solide power racks med mange huller, pull-up-stang og tilbehør ligger i den høje ende. Husk at regne stang, skiver og bænk med i budgettet.</p>

<h2>Sådan sætter du racket op</h2>
<ol>
<li><strong>Vælg placering:</strong> et plant gulv med god loftshøjde og plads til stangen på tværs.</li>
<li><strong>Læg gulv:</strong> gummifliser under hele området, hvor du løfter.</li>
<li><strong>Saml efter vejledningen:</strong> Spænd boltene, og tjek dem igen efter de første træninger.</li>
<li><strong>Fastgør eller vægt racket:</strong> Bolt det fast, hvis producenten anbefaler det, eller placér vægtskiver på opbevaringspindene for stabilitet.</li>
<li><strong>Find dine højder:</strong> Notér, hvilke huller J-hooks og sikkerhedsstænger skal stå i til squat og bænkpres.</li>
</ol>

<h2>Øvelser i et power rack</h2>
<ul>
<li><strong>Squat:</strong> stangen på ryggen, sikkerhedsstængerne lige under bunden af bevægelsen.</li>
<li><strong>Bænkpres:</strong> bænken i racket og sikkerhedsstængerne lige under brystet.</li>
<li><strong>Skulderpres stående:</strong> stangen tages fra J-hooks i brysthøjde.</li>
<li><strong>Rack pulls og markløft:</strong> fra sikkerhedsstængerne eller gulvet.</li>
<li><strong>Pull-ups og chin-ups:</strong> hvis racket har en stang.</li>
<li><strong>Inverted rows:</strong> under en stang i hoftehøjde – god ryggøvelse for begyndere.</li>
</ul>

<h2>Typiske fejl ved køb</h2>
<ul>
<li><strong>Racket er for højt til loftet:</strong> Mål både loft og din egen højde med armene oppe ved pull-ups.</li>
<li><strong>Stang og skiver passer ikke:</strong> Olympisk stang kræver skiver med stort hul.</li>
<li><strong>Bænken passer ikke ind:</strong> Tjek bredden mellem stolperne.</li>
<li><strong>For lidt gulvplads:</strong> Der skal være plads til at læsse skiver på begge sider.</li>
</ul>

