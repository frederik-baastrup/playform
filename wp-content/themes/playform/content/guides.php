require_once ABSPATH . 'wp-admin/includes/media.php';
require_once ABSPATH . 'wp-admin/includes/file.php';
require_once ABSPATH . 'wp-admin/includes/image.php';

$author = get_users( [ 'role' => 'administrator', 'number' => 1 ] );
foreach ( $guides as $g ) {
	$existing = get_page_by_path( $g['slug'], OBJECT, 'post' );
	$cat      = term_exists( $g['cat'], 'category' ) ?: wp_insert_term( $g['cat'], 'category' );
	$data     = [
		'post_type'     => 'post',
		'post_status'   => 'draft',
		'post_name'     => $g['slug'],
		'post_title'    => $g['title'],
		'post_excerpt'  => $g['excerpt'],
		'post_content'  => trim( $g['html'] ),
		'post_category' => [ (int) ( is_array( $cat ) ? $cat['term_id'] : $cat ) ],
		'post_author'   => $author ? $author[0]->ID : 1,
	];
	if ( $existing ) {
		$data['ID'] = $existing->ID;
		unset( $data['post_status'] );
	}
	$id = wp_insert_post( $data );
	if ( ! has_post_thumbnail( $id ) ) {
		$src = get_template_directory() . '/assets/img/' . $g['img'];
		$tmp = wp_tempnam( $g['img'] );
		copy( $src, $tmp );
		$att = media_handle_sideload( [ 'name' => $g['slug'] . '.jpg', 'tmp_name' => $tmp ], $id );
		if ( ! is_wp_error( $att ) ) {
			set_post_thumbnail( $id, $att );
		}
	}
	echo "✓ {$g['title']} (id $id)\n";
}
